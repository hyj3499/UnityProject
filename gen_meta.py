def folder_meta(guid):
    return f"""fileFormatVersion: 2
guid: {guid}
folderAsset: yes
DefaultImporter:
  externalObjects: {{}}
  userData: 
  assetBundleName: 
  assetBundleVariant: 
"""

def default_meta(guid):
    return f"""fileFormatVersion: 2
guid: {guid}
DefaultImporter:
  externalObjects: {{}}
  userData: 
  assetBundleName: 
  assetBundleVariant: 
"""

def script_meta(guid):
    return f"""fileFormatVersion: 2
guid: {guid}
MonoImporter:
  externalObjects: {{}}
  serializedVersion: 2
  defaultReferences: []
  executionOrder: 0
  icon: {{instanceID: 0}}
  userData: 
  assetBundleName: 
  assetBundleVariant: 
"""

count = 0
for dirpath, dirnames, filenames in os.walk(ROOT):
    # folder meta (skip the Assets root itself)
    if dirpath != ROOT:
        rel = os.path.relpath(dirpath, os.path.dirname(ROOT))
        g = guid_for(rel)
        with open(dirpath + ".meta", "w") as f:
            f.write(folder_meta(g))
        count += 1
    for fn in filenames:
        if fn.endswith(".meta"):
            continue
        full = os.path.join(dirpath, fn)
        rel = os.path.relpath(full, os.path.dirname(ROOT))
        g = guid_for(rel)
        metapath = full + ".meta"
        if fn.endswith(".png"):
            content = png_meta(g)
        elif fn.endswith(".cs"):
            content = script_meta(g)
        else:
            content = default_meta(g)
        with open(metapath, "w") as f:
            f.write(content)
        count += 1

print(f"Wrote {count} .meta files")
