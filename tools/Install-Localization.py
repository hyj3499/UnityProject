"""Install verified dropdown hierarchies and explicit text bindings without reserializing the map.

Run Check-Localization.ps1 first. Existing unrelated Unity YAML records stay byte-for-byte unchanged.
"""
from pathlib import Path
import ast
import json
import re
import shutil

ROOT = Path(__file__).resolve().parents[1]
CHECKS = ROOT / "Library/LocalizationChecks"
assert (CHECKS / "Output/result.txt").read_text().startswith("PASS:")
assert (CHECKS / "Output/play-result.txt").read_text().startswith("PASS:")
assert "m_Name: Separator" in (CHECKS / "Assets/Generated/Language.prefab").read_text(), "Generate the current dropdown templates before installation"


def guid(path):
    return re.search(r"^guid: (\w+)", Path(str(path) + ".meta").read_text(), re.M)[1]


def scalar(value):
    value = value.strip()
    if value.startswith('"'):
        return ast.literal_eval(re.sub(r"\n\s+", " ", value))
    if value.startswith("'"):
        return value[1:-1].replace("''", "'")
    return value


def read_docs(text):
    return [[m[1], m[2], m[3]] for m in re.finditer(r"^--- !u!(\d+) &(-?\d+)[^\n]*\n(.*?)(?=^--- !u!|\Z)", text, re.M | re.S)]


def field(body, name):
    match = re.search(r"^  " + re.escape(name) + r": \{fileID: (-?\d+)\}", body, re.M)
    return match[1] if match else None


english, known = {}, {}
for locale in ("en", "ko"):
    for path in sorted((ROOT / "Assets/Resources/Localization" / locale / "Strings").glob("*.json")):
        for entry in json.loads(path.read_text(encoding="utf-8"))["entries"]:
            if locale == "en":
                english[entry["key"]] = entry["value"]
            if not entry["key"].startswith(("npc.", "events.")) and entry["value"]:
                known.setdefault(entry["value"], entry["key"])
known.update({"NEW GAME": "ui.menu.new_game", "CONTINUE": "ui.menu.continue", "SETTING": "ui.menu.settings", "SETTINGS": "ui.menu.settings", "EXIT": "ui.menu.exit", "name": "ui.character.name"})

binding_guid = guid(ROOT / "Assets/Scripts/Localization/LocalizedText.cs")
view_guid = guid(ROOT / "Assets/Scripts/UI/StartScreenView.cs")
own_guids = {guid(p) for p in (ROOT / "Assets/Scripts").rglob("*.cs") if Path(str(p) + ".meta").exists()}

# Fonts generated by Unity retain their own GUIDs and references to the pack's source TTF.
for path in list((CHECKS / "Assets/Resources/Localization").rglob("* SDF.asset*")) + list((CHECKS / "Assets/Resources/Localization").glob("systemfont1 Count.mat*")):
    target = ROOT / "Assets/Resources/Localization" / path.relative_to(CHECKS / "Assets/Resources/Localization")
    shutil.copyfile(path, target)


def install(path):
    original = path.read_bytes()
    source = original.decode("utf-8-sig").replace("\r\n", "\n")
    headers = {m[2]: m[0] for m in re.finditer(r"^--- !u!(\d+) &(-?\d+)[^\n]*", source, re.M)}
    docs = read_docs(source)
    by_id = {d[1]: d for d in docs}
    ids = set(by_id)
    next_id = 9800000000000

    def allocate():
        nonlocal next_id
        while str(next_id) in ids:
            next_id += 1
        value = str(next_id); ids.add(value); next_id += 1
        return value

    def append(kind, ident, body):
        doc = [kind, ident, body]; docs.append(doc); by_id[ident] = doc

    def go_of(component):
        return field(by_id[component][2], "m_GameObject")

    def transform_of(go):
        return next(d for d in docs if d[0] in ("4", "224") and field(d[2], "m_GameObject") == go)

    def children(parent):
        return [d for d in docs if d[0] in ("4", "224") and field(d[2], "m_Father") == parent]

    def name_of(go):
        return scalar(re.search(r"^  m_Name: (.*)$", by_id[go][2], re.M)[1])

    def move(rect, x, y, width=None, height=None):
        rect[2] = re.sub(r"m_AnchoredPosition: \{[^}]+\}", f"m_AnchoredPosition: {{x: {x}, y: {y}}}", rect[2])
        if width is not None:
            rect[2] = re.sub(r"m_SizeDelta: \{[^}]+\}", f"m_SizeDelta: {{x: {width}, y: {height}}}", rect[2])

    def subtree(records, root_transform):
        transforms = {root_transform}
        while True:
            added = {d[1] for d in records if d[0] in ("4", "224") and field(d[2], "m_Father") in transforms} - transforms
            if not added: break
            transforms.update(added)
        objects = {field(d[2], "m_GameObject") for d in records if d[1] in transforms}
        return [d for d in records if d[1] in objects or field(d[2], "m_GameObject") in objects]

    def upgrade_dropdown(component_id, name):
        dropdown = by_id[component_id]
        template_id = field(dropdown[2], "m_Template")
        old = subtree(docs, template_id)
        # Leave a previously upgraded hierarchy intact.
        if any("  m_Name: Separator\n" in d[2] for d in old): return
        generated = read_docs((CHECKS / "Assets/Generated" / (name + ".prefab")).read_text(encoding="utf-8-sig"))
        source_dropdown = next(d for d in generated if "  m_Template:" in d[2])
        source_template = field(source_dropdown[2], "m_Template")
        replacement = subtree(generated, source_template)
        mapping = {d[1]: allocate() for d in replacement}
        parent = transform_of(go_of(component_id))
        old_ids = {d[1] for d in old}
        docs[:] = [d for d in docs if d[1] not in old_ids]
        for ident in old_ids: by_id.pop(ident, None)
        ids.difference_update(old_ids)
        for kind, ident, body in replacement:
            body = re.sub(r"\{fileID: (-?\d+)\}", lambda m: "{fileID: " + mapping.get(m[1], m[1]) + "}", body)
            if ident == source_template:
                body = re.sub(r"m_Father: \{fileID: -?\d+\}", "m_Father: {fileID: " + parent[1] + "}", body)
            append(kind, mapping[ident], body)
        parent[2] = parent[2].replace("  - {fileID: " + template_id + "}", "  - {fileID: " + mapping[source_template] + "}")
        for member in ("m_Template", "m_ItemText"):
            value = mapping[field(source_dropdown[2], member)]
            dropdown[2] = re.sub(r"(^  " + member + r": )\{fileID: -?\d+\}", lambda m: m[1] + "{fileID: " + value + "}", dropdown[2], flags=re.M)

    views = [d for d in docs if "guid: " + view_guid in d[2]]
    for view in views:
        settings = transform_of(field(view[2], "settingsPanel"))
        if field(view[2], "language"):
            upgrade_dropdown(field(view[2], "language"), "Language")
            upgrade_dropdown(field(view[2], "resolution"), "Resolution")
        if not field(view[2], "language"):
            move(settings, 0, 0, 720, 640)
            for child in children(settings[1]):
                name = name_of(go_of(child[1]))
                if name == "Title": move(child, 0, 250)
                if name == "VolumeLabel": move(child, -230, 155)
            move(transform_of(go_of(field(view[2], "volume"))), 70, 155)
            move(transform_of(go_of(field(view[2], "settingsBack"))), 298, 250, 48, 48)
            for name in ("Resolution", "Language", "ResolutionLabel", "LanguageLabel"):
                generated = read_docs((CHECKS / "Assets/Generated" / (name + ".prefab")).read_text(encoding="utf-8-sig"))
                mapping = {d[1]: allocate() for d in generated}
                root = next(d for d in generated if d[0] == "224" and field(d[2], "m_Father") == "0")
                dropdown = next((d for d in generated if d[0] == "114" and "  m_Template:" in d[2]), None)
                for kind, ident, body in generated:
                    body = re.sub(r"\{fileID: (-?\d+)\}", lambda m: "{fileID: " + mapping.get(m[1], m[1]) + "}", body)
                    if ident == root[1]:
                        body = body.replace("m_Father: {fileID: 0}", "m_Father: {fileID: " + settings[1] + "}")
                    body = body.replace("  fontLanguage: ko", "  fontLanguage: ")
                    append(kind, mapping[ident], body)
                settings[2] = settings[2].replace("  m_Children:\n", "  m_Children:\n  - {fileID: " + mapping[root[1]] + "}\n", 1)
                if dropdown:
                    view[2] += "  " + name.lower() + ": {fileID: " + mapping[dropdown[1]] + "}\n"
        # Part captions are also shared text keys, never separate language copies of the logic.
        view[2] = re.sub(r"^(  - label: )(.+)$", lambda m: m[1] + json.dumps("@" + known[scalar(m[2])]) if scalar(m[2]) in known else m[0], view[2], flags=re.M)

    texts = {d[1]: d for d in docs if d[0] == "114" and re.search(r"^  m_(?:Text|text):", d[2], re.M)}
    dynamic, name_fonts, system_texts = set(), set(), set()
    for doc in docs:
        script = re.search(r"m_Script: .*guid: (\w+)", doc[2])
        if script and script[1] in own_guids:
            for key, target in re.findall(r"^  (\w+): \{fileID: (-?\d+)\}", doc[2], re.M):
                if target in texts and not key.endswith("Header"):
                    dynamic.add(target)
                    if key in ("playerName", "saveName"): name_fonts.add(target)
                    if key in ("dateText", "timeText"): system_texts.add(target)
        if "  m_CharacterLimit:" in doc[2]:
            target = field(doc[2], "m_TextComponent")
            if target: dynamic.add(target); name_fonts.add(target)
    for view in views:
        yes_go = go_of(field(view[2], "modalYes"))
        for child in children(transform_of(yes_go)[1]):
            dynamic.update(i for i, text in texts.items() if go_of(i) == go_of(child[1]))

    bound = {field(d[2], "m_GameObject"): d for d in docs if "guid: " + binding_guid in d[2]}
    for ident, text in texts.items():
        go = go_of(ident)
        name = name_of(go)
        count_style = name == "Count"
        system_font = count_style or ident in system_texts
        if go in bound and not system_font: continue
        value_match = re.search(r'^  m_(?:Text|text): ("(?:[^"\\]|\\.)*"|\'(?:[^\']|\'\')*\'|[^\n]*)(?=\n)', text[2], re.M | re.S)
        value = scalar(value_match[1]) if value_match else ""
        key = "" if ident in dynamic else known.get(value, "")
        role = int(any(word in name for word in ("Title", "Heading", "Header")) or bool(re.search(r"m_FontStyle: [13]", text[2])))
        if system_font: role = 2; key = ""
        locale = "ko" if ident in name_fonts and "  m_Text:" in text[2] else ""
        component_id = bound[go][1] if go in bound else allocate()
        if go not in bound:
            by_id[go][2] = by_id[go][2].replace("  m_Component:\n", "  m_Component:\n  - component: {fileID: " + component_id + "}\n", 1)
        binding_body = f'''MonoBehaviour:
  m_ObjectHideFlags: 0
  m_CorrespondingSourceObject: {{fileID: 0}}
  m_PrefabInstance: {{fileID: 0}}
  m_PrefabAsset: {{fileID: 0}}
  m_GameObject: {{fileID: {go}}}
  m_Enabled: 1
  m_EditorHideFlags: 0
  m_Script: {{fileID: 11500000, guid: {binding_guid}, type: 3}}
  m_Name: 
  m_EditorClassIdentifier: Assembly-CSharp::FarmMVP.LocalizedText
  key: {key}
  fontRole: {role}
  inventoryCount: {int(count_style)}
  fontLanguage: {locale}
'''
        if go in bound: bound[go][2] = binding_body
        else: append("114", component_id, binding_body)
        if key:
            text[2] = text[2][:value_match.start(1)] + json.dumps(english[key], ensure_ascii=True) + text[2][value_match.end(1):]
        # Legacy and TMP authoring previews both use the default English pack.
        font_root = ROOT / "Assets/Resources/Localization" / (locale or "en") / "Fonts"
        font_name = "bold" if role else "default"
        if system_font:
            font_root = ROOT / "Assets/Resources/Localization"
            font_name = "systemfont1"
        if count_style:
            text[2] = re.sub(r"(m_Color|m_fontColor): \{[^}]+\}", r"\1: {r: 1, g: 1, b: 1, a: 1}", text[2])
            text[2] = re.sub(r"(m_fontColor32:\n    serializedVersion: 2\n    rgba:) \d+", r"\1 4294967295", text[2])
        if "  m_Text:" in text[2]:
            text[2] = re.sub(r"m_Font: \{[^}]+\}", "m_Font: {fileID: 12800000, guid: " + guid(font_root / (font_name + ".ttf")) + ", type: 3}", text[2])
        else:
            asset = font_root / (font_name + " SDF.asset")
            text[2] = re.sub(r"m_fontAsset: \{[^}]+\}", "m_fontAsset: {fileID: 11400000, guid: " + guid(asset) + ", type: 2}", text[2])
            material_id = re.search(r"^--- !u!21 &(-?\d+)", asset.read_text(encoding="utf-8"), re.M)[1]
            material_guid = guid(asset)
            if count_style: material_guid = guid(font_root / "systemfont1 Count.mat"); material_id = "2100000"
            text[2] = re.sub(r"m_sharedMaterial: \{[^}]+\}", "m_sharedMaterial: {fileID: " + material_id + ", guid: " + material_guid + ", type: 2}", text[2])
        bound[go] = by_id[component_id]
    # Keep original order; scene root record stays at the end.
    docs.sort(key=lambda d: d[0] == "1660057539")
    output = source[:source.index("--- !u!")] + "".join(headers.get(ident, f"--- !u!{kind} &{ident}") + "\n" + body for kind, ident, body in docs)
    assert len(ids) == len(docs), "Duplicate YAML object IDs"
    assert path.read_bytes() == original, "File changed during migration"
    if output != source:
        backup = ROOT / "Library/LocalizationInstallBackup" / path.relative_to(ROOT)
        backup.parent.mkdir(parents=True, exist_ok=True)
        if not backup.exists(): backup.write_bytes(original)
        path.write_text(output, encoding="utf-8", newline="\n")
    print(path.relative_to(ROOT), "localized text objects:", len(texts))


for path in [ROOT / "Assets/Scenes/Main.unity", ROOT / "Assets/Resources/UI/StartScreenUI.prefab", ROOT / "Assets/Prefabs/UI/ShopBookUi.prefab"]:
    install(path)
